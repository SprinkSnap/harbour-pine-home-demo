export function getProductBySlug(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return products.find((product) => product.id === id);
}

export function getFeaturedProducts(limit = 8): Product[] {
  return products.filter((product) => product.featured).slice(0, limit);
}

export function getNewArrivals(limit = 8): Product[] {
  return products.filter((product) => product.newArrival).slice(0, limit);
}

export function getProductsByCollection(slug: string): Product[] {
  return products.filter((product) => product.collection === slug);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const related = product.relatedProductIds
    .map((id) => getProductById(id))
    .filter((item): item is Product => Boolean(item));
  if (related.length >= limit) return related.slice(0, limit);
  const fillers = products.filter(
    (item) => item.collection === product.collection && item.id !== product.id && !related.some((r) => r.id === item.id),
  );
  return [...related, ...fillers].slice(0, limit);
}
